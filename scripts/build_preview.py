#!/usr/bin/env python3
"""Build a GitHub-profile-style HTML preview of all static assets.

Usage:
    python scripts/build_preview.py [out.html]

Defaults to a temp file and prints its path. Purely a QA tool — not part of
the generated profile; the live profile is README.md + assets/*.svg.
"""
import os
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "assets")


def svg(name):
    with open(os.path.join(ASSETS, name), encoding="utf-8") as f:
        return f.read()


def badge(label, msg, color):
    w = 13 * (len(label) + len(msg)) + 70
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="28" role="img">'
        f'<rect width="{w - 1}" height="27" rx="4" fill="#0D0B18"/>'
        f'<rect x="0.5" y="0.5" width="{w - 2}" height="26" rx="3.5" fill="none" stroke="{color}" stroke-opacity="0.55"/>'
        f'<text x="14" y="19" font-family="Segoe UI,sans-serif" font-size="12.5" font-weight="700" fill="#8f8aab">{label}</text>'
        f'<text x="{14 + 13 * len(label) + 12}" y="19" font-family="Segoe UI,sans-serif" font-size="12.5" font-weight="700" fill="{color}">{msg}</text>'
        f"</svg>"
    )


def build(out=None):
    if out is None:
        out = os.path.join(tempfile.gettempdir(), "kilo_profile_preview.html")

    banner = svg("banner.svg")
    stack = svg("stack.svg")
    experience = svg("experience.svg")
    projects = "".join(
        svg(f)
        for f in [
            "project-hr-erp.svg",
            "project-futurex-pos.svg",
            "project-futurex-erp.svg",
            "project-rasha7ly.svg",
            "project-stylish.svg",
            "project-portfolio.svg",
        ]
    )
    stats_pair = svg("stats.svg") + svg("languages.svg")

    html = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Preview — Ibrahim Mohamed GitHub Profile</title>
<style>
  @media (prefers-color-scheme: light) {{ :root {{ --bg: #f6f8fa; --fg: #24292f; }} }}
  body {{ margin: 0; background: #0d1117; color: #c9d1d9; font-family: -apple-system, BlinkMacSystemFont, Segoe UI, sans-serif; }}
  .wrap {{ max-width: 1012px; margin: 0 auto; padding: 40px 24px 80px; }}
  .center {{ text-align: center; }}
  .badge {{ display: inline-block; margin: 0 6px 10px 0; }}
  svg {{ display: block; max-width: 100%; height: auto; border-radius: 14px; }}
  .card-img {{ border-radius: 14px; }}
  h2 {{ color: #e6edf3; font-size: 24px; font-weight: 600; margin: 0 0 16px; border-bottom: 1px solid #30363d; padding-bottom: 8px; }}
  p {{ color: #c9d1d9; line-height: 1.6; margin: 0 0 16px; }}
  a {{ color: #58a6ff; text-decoration: none; }}
  a:hover {{ text-decoration: underline; }}
  .sep {{ height: 24px; }}
  .grid {{ display: flex; flex-wrap: wrap; gap: 2%; justify-content: center; }}
  .grid > * {{ width: 49%; margin-bottom: 2%; }}
  .small {{ color: #8b949e; font-size: 13px; }}
  .tags {{ display: flex; gap: 6px; flex-wrap: wrap; margin-top: 10px; }}
  .tag {{ background: #161b22; border: 1px solid #30363d; color: #c9d1d9; padding: 2px 10px; border-radius: 12px; font-size: 12px; }}
</style>
</head>
<body>
<div class="wrap">
  {banner}
  <div class="sep"></div>
  <div class="center">
    {badge("Portfolio", "himego.vercel.app", "#8B5CF6")}
    {badge("LinkedIn", "Ibrahim Mohamed", "#22D3EE")}
    {badge("Email", "Get in touch", "#8B5CF6")}
    {badge("Archai Solutions", "Website", "#22D3EE")}
  </div>
  <div class="sep"></div>

  <h2>About</h2>
  <p>I'm a software engineer from Egypt who specializes in <strong>Flutter and Dart</strong>. I build mobile and Windows desktop applications for real business workflows: orders, payments, role-based access, receipt printing and API-driven back offices.</p>
  <p>I care about codebases that stay maintainable. I structure apps with <strong>Clean Architecture</strong> and <strong>Cubit / BLoC</strong>, integrate REST APIs with <strong>Dio</strong> (interceptors, refresh tokens, session handling), and use <strong>Firebase</strong> and <strong>Hive</strong> when an app needs cloud sync or offline-first behavior. On the web, I build with <strong>React, TypeScript and Supabase</strong>.</p>

  <div class="sep"></div>
  <h2>Tech Stack</h2>
  {stack}

  <div class="sep"></div>
  <h2>Featured Work</h2>
  <p class="small">FutureX projects are private company work, so their source code is not public. Click Archai HR ERP or Portfolio to open them.</p>
  <div class="grid">{projects}</div>

  <div class="sep"></div>
  <h2>Experience</h2>
  {experience}

  <div class="sep"></div>
  <h2>GitHub Stats</h2>
  <div class="grid">{stats_pair}</div>
  <p class="small">Generated by a GitHub Action in this repository and refreshed daily. No third-party service is involved.</p>

  <div class="sep"></div>
  <h2>Let's Connect</h2>
  <p>I'm looking for remote opportunities where I can build Flutter and software products with a strong engineering team.</p>
  <ul>
    <li><strong>Email:</strong> <a href="mailto:ibrahimmohamed09854@gmail.com">ibrahimmohamed09854@gmail.com</a></li>
    <li><strong>LinkedIn:</strong> <a href="https://www.linkedin.com/in/ibrahim-mohamedx">linkedin.com/in/ibrahim-mohamedx</a></li>
    <li><strong>Portfolio:</strong> <a href="https://himego.vercel.app/">himego.vercel.app/</a></li>
    <li><strong>Archai Solutions:</strong> <a href="https://archaisolutions.vercel.app">archaisolutions.vercel.app</a> · <a href="https://github.com/Archai-Solution">GitHub organization</a></li>
  </ul>
</div>
</body>
</html>"""

    with open(out, "w", encoding="utf-8") as f:
        f.write(html)
    print("preview:", out)
    return out


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else None)
